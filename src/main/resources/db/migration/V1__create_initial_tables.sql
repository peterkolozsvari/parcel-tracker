CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    full_name     VARCHAR(100)             NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(30)              NOT NULL,
    active        BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users
        PRIMARY KEY (id),

    CONSTRAINT uk_users_email
        UNIQUE (email),

    CONSTRAINT chk_users_role
        CHECK (role IN ('CUSTOMER', 'COURIER', 'ADMIN'))
);


CREATE TABLE addresses
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    country      VARCHAR(100) NOT NULL,
    postal_code  VARCHAR(20)  NOT NULL,
    city         VARCHAR(100) NOT NULL,
    street       VARCHAR(150) NOT NULL,
    house_number VARCHAR(20)  NOT NULL,
    door         VARCHAR(50),

    CONSTRAINT pk_addresses
        PRIMARY KEY (id)
);


CREATE TABLE shipments
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tracking_number     VARCHAR(50)              NOT NULL,
    sender_id            BIGINT                   NOT NULL,
    courier_id           BIGINT,
    pickup_address_id    BIGINT                   NOT NULL,
    delivery_address_id  BIGINT                   NOT NULL,
    receiver_name        VARCHAR(100)             NOT NULL,
    status               VARCHAR(30)              NOT NULL DEFAULT 'REGISTERED',
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_shipments
        PRIMARY KEY (id),

    CONSTRAINT uk_shipments_tracking_number
        UNIQUE (tracking_number),

    CONSTRAINT chk_shipments_status
        CHECK (
            status IN (
                       'REGISTERED',
                       'COURIER_ASSIGNED',
                       'PICKED_UP',
                       'IN_TRANSIT',
                       'DELIVERED',
                       'DELIVERY_FAILED',
                       'CANCELLED'
                )
            ),

    CONSTRAINT fk_shipments_sender
        FOREIGN KEY (sender_id)
            REFERENCES users (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_shipments_courier
        FOREIGN KEY (courier_id)
            REFERENCES users (id)
            ON DELETE SET NULL,

    CONSTRAINT fk_shipments_pickup_address
        FOREIGN KEY (pickup_address_id)
            REFERENCES addresses (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_shipments_delivery_address
        FOREIGN KEY (delivery_address_id)
            REFERENCES addresses (id)
            ON DELETE RESTRICT
);


CREATE TABLE parcels
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shipment_id BIGINT        NOT NULL,
    weight      NUMERIC(10, 2) NOT NULL,
    description VARCHAR(500),
    is_fragile  BOOLEAN        NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_parcels
        PRIMARY KEY (id),

    CONSTRAINT chk_parcels_weight
        CHECK (weight > 0),

    CONSTRAINT fk_parcels_shipment
        FOREIGN KEY (shipment_id)
            REFERENCES shipments (id)
            ON DELETE CASCADE
);


CREATE TABLE tracking_events
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    shipment_id        BIGINT                   NOT NULL,
    changed_by_user_id BIGINT,
    status             VARCHAR(30)              NOT NULL,
    description        VARCHAR(500),
    occurred_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tracking_events
        PRIMARY KEY (id),

    CONSTRAINT chk_tracking_events_status
        CHECK (
            status IN (
                       'REGISTERED',
                       'COURIER_ASSIGNED',
                       'PICKED_UP',
                       'IN_TRANSIT',
                       'DELIVERED',
                       'DELIVERY_FAILED',
                       'CANCELLED'
                )
            ),

    CONSTRAINT fk_tracking_events_shipment
        FOREIGN KEY (shipment_id)
            REFERENCES shipments (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_tracking_events_changed_by_user
        FOREIGN KEY (changed_by_user_id)
            REFERENCES users (id)
            ON DELETE SET NULL
);


CREATE INDEX idx_shipments_sender_id
    ON shipments (sender_id);

CREATE INDEX idx_shipments_courier_id
    ON shipments (courier_id);

CREATE INDEX idx_shipments_status
    ON shipments (status);

CREATE INDEX idx_parcels_shipment_id
    ON parcels (shipment_id);

CREATE INDEX idx_tracking_events_shipment_id
    ON tracking_events (shipment_id);